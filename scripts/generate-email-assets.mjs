import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

const root = new URL("../", import.meta.url);
const logoSvg = await readFile(new URL("public/omnibudget.svg", root));
const guillocheSvg = await readFile(new URL("public/guilloche.svg", root), "utf8");

// Render the existing artwork, not a new pattern. Crop well inside the original
// edges and away from the barycenter, as on the landing page. Email is static.
const guillocheCrop = guillocheSvg
  .replace(/<style>[\s\S]*?<\/style>/, "")
  .replace('viewBox="0 0 240 500"', 'viewBox="55 45 156 132" width="1040" height="880"')
  .replace('stroke="#1a652a"', 'stroke="#1a652a" opacity="0.18" stroke-width="1.5"');

const options = { compressionLevel: 9, palette: true, colours: 128, dither: 0 };
const logo = await sharp(logoSvg, { density: 216 })
  .resize({ width: 660 })
  .png(options)
  .toBuffer({ resolveWithObject: true });
const guilloche = await sharp(Buffer.from(guillocheCrop))
  .flatten({ background: "#fbf8f4" })
  .png(options)
  .toBuffer({ resolveWithObject: true });

const assets = {
  description: "Generated by npm run email:assets from the original public SVGs. Do not edit manually.",
  logo: { width: logo.info.width, height: logo.info.height, base64: logo.data.toString("base64") },
  guilloche: { width: guilloche.info.width, height: guilloche.info.height, base64: guilloche.data.toString("base64") },
};

await writeFile(new URL("src/emails/assets.generated.json", root), `${JSON.stringify(assets, null, 2)}\n`);
console.log(`Embedded email artwork: ${logo.data.length + guilloche.data.length} bytes (PNG)`);
